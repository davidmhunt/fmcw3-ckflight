#!/usr/bin/env python3
"""Fetch and check the datasheets, vendor models and references the analyses rely on.

Three manifests (YAML, top-level key `entries:`, a list):
  datasheets/manifest.yaml        datasheets and vendor models
  software/manifest.yaml          tool installers (see software/README.md)
  docs/references/manifest.yaml   papers, textbooks, app notes, documents

Entry fields: id, kind, title, url (public), access (direct|form|login), file (path
relative to the repo root), sha256, licence, commit (yes|no). Reference entries also carry
`verified:`, a list of {page, item, quote} read from the downloaded file.

  fetch_sources.py            download `direct` entries, print a to-do list for the rest; a
                              failed download is kept going past and recorded on the entry
                              (`fetch_error`); writes docs/user-fetch.md (pending items)
                              An entry with `digikey: <MPN>` and no file is looked up through
                              the DigiKey Product Information API (parts/check_digikey.py's
                              client, keys from .env, answers cached under parts/cache/digikey/);
                              the returned datasheet URL is tried first, then the entry's `url`;
                              each download must be a PDF. When both fail the entry is pending
                              and records `digikey_url` (the API's ProductUrl) for its row.
  fetch_sources.py --check   fail on a missing file, a hash mismatch, or a reference
                              with no `verified` item. A form or login entry with no file
                              (or a direct one with a `fetch_error`) and no sha256 yet is
                              listed as PENDING, not failed.
  fetch_sources.py --record   also write the sha256 of files that have none yet
  fetch_sources.py --add URL --id ID --kind KIND --title TEXT --file PATH
                              [--licence TEXT] [--commit yes|no] [--manifest PATH]
                              download URL, hash it, append an entry (commit: no by default)

Files with `commit: no` must live under a `files/` directory, which .gitignore covers.
Only a licence that allows redistribution may use `commit: yes`.
"""
import argparse
import hashlib
import sys
import urllib.request
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANIFESTS = [
    ("datasheets/manifest.yaml", False),
    ("software/manifest.yaml", False),
    ("docs/references/manifest.yaml", True),
]
REQUIRED = ("id", "kind", "title", "url", "access", "file", "sha256", "licence", "commit")
ACCESS = ("direct", "form", "login")


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load(path):
    data = yaml.safe_load(Path(path).read_text()) or {}
    entries = data.get("entries") or []
    if not isinstance(entries, list):
        raise ValueError(f"{path}: `entries` must be a list")
    return entries


def commit_flag(entry):
    return str(entry.get("commit")).lower() in ("yes", "true")


def is_pending(entry, root=ROOT):
    """An entry the user has to fetch by hand and with no hash pinned: a form or login entry
    without a file, or a direct entry whose download failed (`fetch_error`). A to-do, not a
    failure. Once its sha256 is recorded, a missing file fails again."""
    wanted = entry.get("access") in ("form", "login") or (
        entry.get("access") == "direct" and entry.get("fetch_error"))
    return bool(wanted and not entry.get("sha256") and not (root / entry["file"]).is_file())


def pending_links(entry):
    """The link cell of a pending row: the DigiKey product page (when the API gave one), then
    the entry's own url."""
    if entry.get("digikey_url"):
        return f"DigiKey: {entry['digikey_url']} ; maker: {entry['url']}"
    return entry["url"]


def pending_reason(entry):
    if entry.get("fetch_error"):
        return f"download failed: {entry['fetch_error']}"
    return f"not downloadable unattended ({entry['access']} required)"


RECORD_CMD = "./run tools/fetch_sources.py --record"


def write_user_fetch(manifests, root=ROOT, rel="docs/user-fetch.md"):
    """Regenerate docs/user-fetch.md: one row per pending item across the manifests."""
    def cell(text):
        return str(text).replace("|", "\\|").replace("\n", " ")

    rows = pending_all(manifests, root)
    lines = [
        "# Things you fetch by hand",
        "",
        "Generated by `./run tools/fetch_sources.py`; do not edit. Each row is a source that could",
        "not be downloaded unattended. Save the file at the path shown, then run",
        f"`{RECORD_CMD}` to pin its hash; the row disappears on the next run.",
        "",
    ]
    if not rows:
        lines.append("Nothing pending.")
    else:
        lines += ["| Item | What it is | Link | Save as | Why not fetched | Then run |",
                  "|---|---|---|---|---|---|"]
        for e in rows:
            lines.append("| " + " | ".join([
                cell(e["id"]), cell(e["title"]), cell(pending_links(e)), f"`{cell(e['file'])}`",
                cell(pending_reason(e)), f"`{RECORD_CMD}`"]) + " |")
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not path.is_file() or path.read_text() != text:
        path.write_text(text)
    return rows


def pending_all(manifests, root=ROOT):
    out = []
    for rel, _ in manifests:
        mpath = root / rel
        if mpath.is_file():
            out += [e for e in load(mpath) if "file" in e and is_pending(e, root)]
    return out


def check_entry(entry, is_reference, root=ROOT):
    """Return a list of problem strings for one entry."""
    eid = entry.get("id", "?")
    problems = []
    for key in REQUIRED:
        if key not in entry:
            problems.append(f"{eid}: missing field {key}")
    if problems:
        return problems
    if entry["access"] not in ACCESS:
        problems.append(f"{eid}: access must be one of {ACCESS}")
    if str(entry["commit"]).lower() not in ("yes", "no", "true", "false"):
        problems.append(f"{eid}: commit must be yes or no")
    if not commit_flag(entry) and "files" not in Path(entry["file"]).parts:
        problems.append(f"{eid}: commit: no needs a path under a files/ directory (gitignored)")
    path = root / entry["file"]
    if not path.is_file():
        if not is_pending(entry, root):
            problems.append(f"{eid}: file missing: {entry['file']}")
    elif not entry["sha256"]:
        problems.append(f"{eid}: no sha256 recorded (run fetch_sources.py --record)")
    elif sha256_of(path) != entry["sha256"]:
        problems.append(f"{eid}: sha256 mismatch for {entry['file']}")
    if is_reference and not entry.get("verified"):
        problems.append(f"{eid}: reference has no verified item")
    return problems


def check_all(manifests, root=ROOT):
    problems = []
    seen = set()
    for rel, is_ref in manifests:
        mpath = root / rel
        if not mpath.is_file():
            problems.append(f"manifest missing: {rel}")
            continue
        for entry in load(mpath):
            if entry.get("id") in seen:
                problems.append(f"{entry.get('id')}: duplicate id")
            seen.add(entry.get("id"))
            problems += check_entry(entry, is_ref, root)
    return problems


def download(url, dest):
    dest.parent.mkdir(parents=True, exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "fetch_sources/1.0"})
    tmp = dest.with_name(dest.name + ".part")
    with urllib.request.urlopen(req, timeout=60) as r, open(tmp, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)
    tmp.replace(dest)


DK_CACHE = ROOT / "parts" / "cache" / "digikey"   # gitignored with the rest of parts/cache/


def https(url):
    """DigiKey returns some datasheet links as `//host/path`."""
    return "https:" + url if url.startswith("//") else url


def check_pdf(path):
    """Raise unless the file carries the PDF magic (an HTML block page does not)."""
    with open(path, "rb") as f:
        head = f.read(1024)
    if b"%PDF-" not in head:
        kind = "an HTML page" if b"<" in head[:200] else "something else"
        raise ValueError(f"not a PDF (got {kind})")


def _dk_module():
    if str(ROOT / "parts") not in sys.path:
        sys.path.insert(0, str(ROOT / "parts"))
    import check_digikey as dk
    return dk


def make_lookup(client=None, cache=DK_CACHE):
    """mpn -> the DigiKey product (dict) or None. Answers are cached like parts/bom.py's
    CachedDigiKey (same key, so its cache is reused). `client` defaults to one built from .env
    on first use, so a run with nothing to look up needs no keys."""
    import hashlib
    import json
    box = {"client": client}

    def lookup(mpn):
        dk = _dk_module()
        path = cache / (hashlib.sha1(f"{mpn}|10".encode()).hexdigest() + ".json")
        if path.is_file():
            products = json.loads(path.read_text())
        else:
            if box["client"] is None:
                box["client"] = dk.Client.from_env()
            products = box["client"].search(mpn, 10)
            cache.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(products))
        return dk.exact_match(products, mpn)
    return lookup


def _try_download(url, path, opener):
    try:
        opener(url, path)
        if not path.is_file():
            raise OSError("download produced no file")
        check_pdf(path)
        return ""
    except Exception as exc:  # noqa: BLE001 - any failure is a reason, not a crash
        path.unlink(missing_ok=True)
        path.with_name(path.name + ".part").unlink(missing_ok=True)
        return " ".join(str(exc).split()) or type(exc).__name__


def fetch_digikey(e, path, opener, lookup):
    """Try the DigiKey datasheet URL, then the entry's own url (direct entries only). Return
    (ok, why, product_url); `why` lists what failed."""
    why, product_url, product = [], "", None
    try:
        product = lookup(e["digikey"])
        if product is None:
            why.append(f"DigiKey API has no exact match for {e['digikey']}")
    except Exception as exc:  # noqa: BLE001 - missing keys, network: fall back to the url
        why.append("DigiKey API: " + (" ".join(str(exc).split())[:200] or type(exc).__name__))
    if product:
        product_url = product.get("ProductUrl") or ""
        dsurl = https(product.get("DatasheetUrl") or "")
        if not dsurl:
            why.append("DigiKey lists no datasheet")
        else:
            print(f"fetching {e['id']} via DigiKey: {dsurl}")
            err = _try_download(dsurl, path, opener)
            if not err:
                return True, "", product_url
            why.append(f"DigiKey datasheet {dsurl}: {err}")
    if e["access"] == "direct":
        print(f"fetching {e['id']}: {e['url']}")
        err = _try_download(e["url"], path, opener)
        if not err:
            return True, "", product_url
        why.append(f"maker url: {err}")
    return False, "; ".join(why), product_url


def _block(lines, start):
    """The lines after `- ` line `start`, up to the next entry."""
    end = start + 1
    while end < len(lines) and not lines[end].startswith("- "):
        end += 1
    return lines[start + 1:end]


def patch_manifest_text(text, updates):
    """Apply {id: {key: value or None}} to the manifest text, line by line, so comments and
    layout survive. A None value deletes the key; a missing key is appended to the entry."""
    lines = text.splitlines()
    for eid, keys in updates.items():
        ids = (f"id: {eid}", f"id: '{eid}'", f'id: "{eid}"')
        start = next((i for i, ln in enumerate(lines)
                      if ln.startswith("- ") and any(
                          ln.rstrip() == "- " + s or any(
                              m.rstrip() == "  " + s for m in _block(lines, i))
                          for s in ids)), None)
        if start is None:
            raise ValueError(f"entry {eid} not found in manifest text")
        for key, value in keys.items():
            end = start + 1
            while end < len(lines) and not lines[end].startswith("- "):
                end += 1
            pos = next((i for i in range(start + 1, end) if lines[i].startswith(f"  {key}:")),
                       None)
            new = []
            if value is not None:
                dumped = yaml.safe_dump({key: value}, width=100).rstrip("\n").split("\n")
                new = ["  " + ln for ln in dumped]
            if pos is not None:
                stop = pos + 1
                while stop < end and lines[stop].startswith("    "):
                    stop += 1
                lines[pos:stop] = new
            elif new:
                at = end
                while at > start + 1 and (not lines[at - 1].strip()
                                          or lines[at - 1].lstrip().startswith("#")):
                    at -= 1
                lines[at:at] = new
    return "\n".join(lines) + "\n"


def fetch_all(manifests, root=ROOT, record=False, opener=download, today=None, lookup=None):
    """Download direct entries that are missing; return the user to-do lines.

    A direct download that fails does not stop the run: the failure is printed, recorded on
    the entry as `fetch_error` (error text and date) and the entry becomes a user-fetch item.
    A saved file clears the `fetch_error` of its entry. An entry with `digikey: <MPN>` goes
    through fetch_digikey (`lookup` replaces the live API, for tests)."""
    today = today or date.today().isoformat()
    todo = []
    for rel, _ in manifests:
        mpath = root / rel
        if not mpath.is_file():
            continue
        entries = load(mpath)
        updates = {}
        for e in entries:
            path = root / e["file"]
            if not path.is_file() and e.get("digikey"):
                lookup = lookup or make_lookup()
                ok, why, purl = fetch_digikey(e, path, opener, lookup)
                if not ok:
                    print(f"FAILED {e['id']}: {why}", file=sys.stderr)
                    e["fetch_error"] = f"{why} ({today})"
                    e["digikey_url"] = purl
                    updates.setdefault(e["id"], {}).update(
                        fetch_error=e["fetch_error"], digikey_url=purl or None)
                    todo.append(f"{e['id']} (download failed: {why}): open "
                                f"{pending_links(e)} and save as {e['file']} "
                                f"[{e['title']}; licence: {e['licence']}]")
                    continue
                e.pop("digikey_url", None)
                updates.setdefault(e["id"], {})["digikey_url"] = None
            elif not path.is_file():
                if e["access"] == "direct":
                    print(f"fetching {e['id']}: {e['url']}")
                    try:
                        opener(e["url"], path)
                        if not path.is_file():
                            raise OSError("download produced no file")
                    except Exception as exc:  # noqa: BLE001 - any failure is a user-fetch item
                        path.with_name(path.name + ".part").unlink(missing_ok=True)
                        msg = " ".join(str(exc).split()) or type(exc).__name__
                        print(f"FAILED {e['id']}: {msg}", file=sys.stderr)
                        e["fetch_error"] = f"{msg} ({today})"
                        updates.setdefault(e["id"], {})["fetch_error"] = e["fetch_error"]
                        todo.append(
                            f"{e['id']} (direct, download failed: {msg}): open {e['url']} and "
                            f"save as {e['file']} [{e['title']}; licence: {e['licence']}]")
                        continue
                else:
                    todo.append(
                        f"{e['id']} ({e['access']}): open {e['url']} and save as {e['file']}"
                        f" [{e['title']}; licence: {e['licence']}]")
                    continue
            if "fetch_error" in e:
                del e["fetch_error"]
                updates.setdefault(e["id"], {})["fetch_error"] = None
            if record and path.is_file() and not e.get("sha256"):
                e["sha256"] = sha256_of(path)
                print(f"recorded sha256 for {e['id']}: {e['sha256']}")
                updates.setdefault(e["id"], {})["sha256"] = e["sha256"]
        if updates:
            # edit the text, not re-dump the data: comments and layout stay
            mpath.write_text(patch_manifest_text(mpath.read_text(), updates))
    return todo


def add_entry(url, eid, kind, title, file, licence="vendor copyright; not redistributed here",
              commit="no", manifest="datasheets/manifest.yaml", root=ROOT, opener=download,
              manifests=MANIFESTS):
    """Download `url` to `file`, hash it and append an entry to `manifest`.

    Returns (ok, message). Nothing is appended when the id exists in any manifest, the commit
    flag and path disagree, or the download fails. The entry is appended as text so comments
    already in the manifest survive."""
    if commit not in ("yes", "no"):
        return False, f"commit must be yes or no, not {commit!r}"
    if commit == "no" and "files" not in Path(file).parts:
        return False, f"commit: no needs a path under a files/ directory (gitignored): {file}"
    for rel, _ in manifests:
        mpath = root / rel
        if mpath.is_file() and any(e.get("id") == eid for e in load(mpath)):
            return False, f"id {eid} already exists in {rel}; not added"
    mpath = root / manifest
    dest = root / file
    if dest.exists():
        return False, f"{file} already exists; not overwritten"
    try:
        opener(url, dest)
    except Exception as exc:  # noqa: BLE001 - any failure is a dead link to the user
        dest.with_name(dest.name + ".part").unlink(missing_ok=True)
        return False, f"download failed for {url}: {exc}"
    if not dest.is_file():
        return False, f"download of {url} produced no file at {file}"
    entry = {"id": eid, "kind": kind, "title": title, "url": url, "access": "direct",
             "file": file, "sha256": sha256_of(dest), "licence": licence, "commit": commit}
    text = mpath.read_text() if mpath.is_file() else "entries:\n"
    if "entries: []" in text:
        text = text.replace("entries: []", "entries:")
    if text and not text.endswith("\n"):
        text += "\n"
    text += yaml.safe_dump([entry], sort_keys=False, width=100)
    mpath.parent.mkdir(parents=True, exist_ok=True)
    mpath.write_text(text)
    return True, f"added {eid} to {manifest}: {file} sha256 {entry['sha256']}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify files, hashes, verified items")
    ap.add_argument("--record", action="store_true", help="record missing sha256 after fetching")
    ap.add_argument("--add", metavar="URL", help="download URL and append a manifest entry "
                    "(needs --id, --kind, --title, --file)")
    ap.add_argument("--id", help="with --add: entry id")
    ap.add_argument("--kind", help="with --add: datasheet, vendor-model, ...")
    ap.add_argument("--title", help="with --add: what it is, refdes, revision")
    ap.add_argument("--file", help="with --add: path under a files/ directory, from the repo root")
    ap.add_argument("--licence", default="vendor copyright; not redistributed here",
                    help="with --add: licence text")
    ap.add_argument("--commit", default="no", choices=("yes", "no"),
                    help="with --add: commit the file (only if the licence allows)")
    ap.add_argument("--manifest", default="datasheets/manifest.yaml",
                    choices=[m for m, _ in MANIFESTS], help="with --add: manifest to append to")
    args = ap.parse_args(argv)
    if args.add:
        missing = [f for f in ("id", "kind", "title", "file") if not getattr(args, f)]
        if missing:
            ap.error("--add needs " + ", ".join("--" + m for m in missing))
        ok, msg = add_entry(args.add, args.id, args.kind, args.title, args.file,
                            licence=args.licence, commit=args.commit, manifest=args.manifest)
        print(msg, file=sys.stdout if ok else sys.stderr)
        return 0 if ok else 1
    if args.check:
        problems = check_all(MANIFESTS)
        for p in problems:
            print("FAIL", p)
        for e in pending_all(MANIFESTS):
            why = f"; {pending_reason(e)}" if e.get("fetch_error") else ""
            print(f"PENDING {e['id']} ({e['access']}, user-fetch, no hash pinned yet{why}): "
                  f"open {pending_links(e)} and save as {e['file']}, then run --record")
        print("sources check:", "FAILED" if problems else "ok")
        return 1 if problems else 0
    todo = fetch_all(MANIFESTS, record=args.record)
    write_user_fetch(MANIFESTS)
    if todo:
        print("\nTo do by hand (not downloadable unattended):")
        for t in todo:
            print(" -", t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
